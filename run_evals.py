"""run_evals.py - CLI entry point.

Two modes, with a deliberate distinction between them:

  mock  Deterministic placeholder scores. Proves the gate wiring. Can never
        authorise a live-quality release.
  real  Generates an answer for each case with a provider, scores *that* answer,
        and records the generated text alongside the scores. Requires
        OPENAI_API_KEY; refuses before loading an SDK without one.

A real run that fails the bar exits non-zero. A real run that produced no answer
for some cases scores those as failures rather than skipping them.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
import math
from pathlib import Path
import statistics

from answer_generator import DEFAULT_MODEL, generate_answers
from evaluator import Evaluator, MissingGeneratedAnswer
from gate_policy import assess_rows, json_safe, load_policy, DEFAULT_POLICY
from golden_set import GoldenSet, GoldenCase


def _bar(raw: str) -> float:
    value = float(raw)
    if not math.isfinite(value) or not 0 <= value <= 1:
        raise argparse.ArgumentTypeError("bar must be finite and between 0 and 1")
    return value


def _render(payload: dict) -> str:
    established = payload.get("live_quality_established", False)
    if established:
        verdict = (
            "Live quality established: true for the recorded sample.\n\n"
            "Each row was generated by the configured provider and scored on the "
            "generated answer. This artifact covers only the cases listed.\n"
        )
    else:
        verdict = (
            "Live quality established: false\n\n"
            "This artifact cannot authorise a live-quality release.\n"
        )
    return (
        "# Evaluation evidence: " + payload["status"] + "\n\n"
        "Execution mode: " + payload["execution_mode"] + "\n\n"
        "Evaluator: " + payload["evaluator_identity"] + "\n\n"
        + verdict
        + "\n```json\n" + json.dumps(payload, indent=2) + "\n```\n"
    )


def write_report(path: Path, payload: dict) -> None:
    payload = json_safe(payload)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(_render(payload), encoding="utf-8")
    path.with_suffix(".json").write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


def _base_payload(args: argparse.Namespace) -> dict:
    return {
        "schema_version": 2,
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "execution_mode": args.mode,
        "evaluator_identity": (
            "deterministic-placeholder-v1" if args.mode == "mock" else "ragas-generated-answer-v1"
        ),
        "evidence_type": "offline_scaffold" if args.mode == "mock" else "live_generated_answer",
        "live_quality_established": False,
        "live_quality_required": args.require_live_quality,
        "thresholds": {"faithfulness": args.threshold, "answer_relevancy": args.relevancy_bar},
        "rows": [],
    }


def main(
    argv: list[str] | None = None,
    complete_fn=None,
    scorer=None,
) -> int:
    """Run the gate.

    ``complete_fn`` and ``scorer`` exist so the test suite can exercise the real
    path's contract - generated answers, never the reference - without network
    access. Both default to ``None``, meaning "use the real provider".
    """
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--mode", choices=["mock", "real"], default="mock")
    ap.add_argument("--threshold", type=_bar, default=None)
    ap.add_argument("--relevancy-bar", type=_bar, default=None)
    ap.add_argument("--report", default="EVAL_REPORT.mock.md")
    ap.add_argument("--require-live-quality", action="store_true",
                    help="Block unless genuine application-quality evidence is available")
    ap.add_argument("--max-cases", type=int, default=0, help="Limit cases (0 = all)")
    ap.add_argument("--model", default=DEFAULT_MODEL, help="Generation model for real mode")
    ap.add_argument("--policy", default=str(DEFAULT_POLICY), help="Versioned real-mode gate policy")
    args = ap.parse_args(argv)
    if args.max_cases < 0:
        ap.error("--max-cases cannot be negative")
    policy = load_policy(args.policy)
    args.threshold = args.threshold if args.threshold is not None else (0.90 if args.mode == "mock" else policy["mean_floors"]["faithfulness"])
    args.relevancy_bar = args.relevancy_bar if args.relevancy_bar is not None else (0.85 if args.mode == "mock" else policy["mean_floors"]["answer_relevancy"])
    policy["mean_floors"] = {"faithfulness": args.threshold, "answer_relevancy": args.relevancy_bar}

    path = Path(args.report)
    if path.suffix.lower() != ".md":
        ap.error("--report must end in .md; a matching .json artifact is also written")

    payload = _base_payload(args)

    # ---- Mock: a scaffold check, never release evidence -------------------
    if args.mode == "mock":
        if args.require_live_quality:
            payload.update(status="blocked",
                           reason="mock mode cannot satisfy a live-quality requirement")
            write_report(path, payload)
            print("LIVE QUALITY BLOCKED: mock mode is a wiring check, not evidence.")
            return 2
        golden = GoldenSet()
        evaluator = Evaluator(mode="mock")
        rows = [{"case": i, "question": c.question, **evaluator.score(c)}
                for i, c in enumerate(golden.cases, start=1)]
        if not rows:
            payload.update(status="blocked", reason="No golden cases")
            write_report(path, payload)
            return 2
        mean_f = statistics.fmean(r["faithfulness"] for r in rows)
        mean_r = statistics.fmean(r["answer_relevancy"] for r in rows)
        ok = mean_f >= args.threshold and mean_r >= args.relevancy_bar
        payload.update(status="offline_pass" if ok else "offline_fail", case_count=len(rows),
                       means={"faithfulness": mean_f, "answer_relevancy": mean_r}, rows=rows)
        write_report(path, payload)
        print(f"OFFLINE SCAFFOLD {'PASSED' if ok else 'FAILED'}: placeholder scores only; "
              "live quality unverified.")
        return 0 if ok else 1

    # ---- Real: generate answers, then score the generated answers ---------
    try:
        evaluator = Evaluator(mode="real", scorer=scorer)
    except RuntimeError as exc:
        # No credential: record a refusal without any provider call and without
        # overwriting the reason with a pass.
        payload.update(status="blocked", reason=str(exc))
        write_report(path, payload)
        print(f"LIVE QUALITY BLOCKED: {exc}")
        return 2

    golden = GoldenSet()
    cases = golden.cases[: args.max_cases] if args.max_cases else golden.cases
    print(f"generating answers for {len(cases)} case(s) with {args.model} ...")
    cases = generate_answers(cases, complete_fn=complete_fn, model=args.model)

    expected_count = len(cases)
    rows: list[dict] = []
    unanswerable = 0
    for i, case in enumerate(cases, start=1):
        judge_error = None
        try:
            scores = evaluator.score(case)
            if not isinstance(scores, dict):
                raise ValueError("judge did not return a metric mapping")
        except MissingGeneratedAnswer as exc:
            # A case with no generated answer is a failure, not a skip.
            unanswerable += 1
            scores = {"faithfulness": 0.0, "answer_relevancy": 0.0, "note": str(exc)}
        except (Exception, SystemExit) as exc:
            judge_error = type(exc).__name__
            scores = {"faithfulness": 0.0, "answer_relevancy": 0.0}
        rows.append({
            "case": i,
            "question": case.question,
            **scores,
            "generated_answer": case.generated_answer,
            "retrieved_contexts": case.retrieved_contexts,
            "judge_error": judge_error,
        })

    outcome = assess_rows(rows, policy, expected_count)
    mean_f = outcome["means"]["faithfulness"]
    mean_r = outcome["means"]["answer_relevancy"]
    ok = outcome["passed"]
    payload.update(
        status="live_pass" if ok else "live_fail",
        case_count=len(rows),
        unanswerable_cases=unanswerable,
        generation_model=args.model,
        policy=policy,
        hard_failures=outcome["hard_failures"],
        means={"faithfulness": mean_f, "answer_relevancy": mean_r},
        rows=rows,
        # True means: answers were produced by a provider and scored on the
        # generated text. It does NOT mean the bar was met - see `status`.
        live_quality_established=True,
    )
    write_report(path, payload)
    print(f"LIVE EVALUATION {'PASSED' if ok else 'FAILED'}: faithfulness {mean_f:.3f} "
          f"(bar {args.threshold}), relevancy {mean_r:.3f} (bar {args.relevancy_bar}); "
          f"{unanswerable} unanswerable case(s).")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
